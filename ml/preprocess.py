_SKIN_TONES = re.compile("[\U0001F3FB-\U0001F3FF]")
_URL = re.compile(r"(https?://\S+|www\.\S+|t\.me/\S+)", re.IGNORECASE)
_MENTION = re.compile(r"@\w+")
_HTML = re.compile(r"<[^>]+>")
_REPEAT_LETTERS = re.compile(r"([а-яёa-z])\1{2,}")
_REPEAT_PUNCT = re.compile(r"([!?.])\1{2,}")
_SPACES = re.compile(r"\s+")


def _emoji_to_words(chars: str, data=None) -> str:
    key = _SKIN_TONES.sub("", chars).replace("\ufe0f", "").replace("\u200d", "")
    word = EMOJI_WORDS.get(key) or EMOJI_WORDS.get(key[:1], "")
    return f" {word} " if word else " "   # неизвестные эмодзи просто убираем


def clean_text(text: str) -> str:
    if not isinstance(text, str):
        return ""
    text = _URL.sub(" ", text)
    text = _MENTION.sub(" ", text)
    text = _HTML.sub(" ", text)
    text = emoji.replace_emoji(text, replace=_emoji_to_words)  # эмодзи -> слова
    text = text.lower()
    text = _REPEAT_LETTERS.sub(r"\1\1", text)   # "оооочень" -> "оочень"
    text = _REPEAT_PUNCT.sub(r"\1\1", text)     # "!!!!!" -> "!!"
    return _SPACES.sub(" ", text).strip()


def has_emoji(text: str) -> bool:
    return isinstance(text, str) and emoji.emoji_count(text) > 0
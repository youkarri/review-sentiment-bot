# Текстовые смайлы: ")))", "((", ":)", ":(" и т.п. (в русских отзывах их очень много)
_SMILE_POS = re.compile(r"(?<![\w(])(?:[:;=]-?[)D\]]|\^_?\^)|\){2,}|\bxd\b", re.IGNORECASE)
_SMILE_NEG = re.compile(r"(?<![\w)])[:;=]'?-?[(\[]|\({2,}")
_SMILE_END = re.compile(r"(?<=\w)\)+\s*$")  # "Спасибо)" - скобка без пары в конце

_SKIN_TONES = re.compile("[\U0001F3FB-\U0001F3FF]")
_URL = re.compile(r"(https?://\S+|www\.\S+|t\.me/\S+)", re.IGNORECASE)
_MENTION = re.compile(r"@\w+")
_HTML = re.compile(r"<[^>]+>")
_REPEAT_LETTERS = re.compile(r"([а-яёa-z])\1{2,}")
_REPEAT_PUNCT = re.compile(r"([!?.])\1{2,}")
_SPACES = re.compile(r"\s+")


def normalize_emoji(chars: str) -> str:
    """Убирает тон кожи, невидимые символы-модификаторы: '👍🏽' -> '👍', '❤️' -> '❤'."""
    return _SKIN_TONES.sub("", chars).replace("\ufe0f", "").replace("\u200d", "")


def _emoji_to_words(chars: str, data=None) -> str:
    key = normalize_emoji(chars)
    word = EMOJI_WORDS.get(key) or EMOJI_WORDS.get(key[:1], "")
    return f" {word} " if word else " "   # неизвестные эмодзи просто убираем


def _emoji_drop(chars: str, data=None) -> str:
    return " "


def _smileys_to_words(text: str) -> str:
    text = _SMILE_NEG.sub(" плохо грустно ", text)
    text = _SMILE_POS.sub(" хорошо ", text)
    if "(" not in text:
        text = _SMILE_END.sub(" хорошо ", text)
    return text


def clean_text(text: str, emoji_mode: str = "words") -> str:
    """emoji_mode="words" - эмодзи и смайлы превращаются в слова (для модели);
    emoji_mode="drop"  - эмодзи и смайлы удаляются (для статистики слов)."""
    if not isinstance(text, str):
        return ""
    text = _URL.sub(" ", text)
    text = _MENTION.sub(" ", text)
    text = _HTML.sub(" ", text)
    if emoji_mode == "words":
        text = _smileys_to_words(text)
        text = emoji.replace_emoji(text, replace=_emoji_to_words)
    else:
        text = _SMILE_NEG.sub(" ", text)
        text = _SMILE_POS.sub(" ", text)
        if "(" not in text:
            text = _SMILE_END.sub(" ", text)
        text = emoji.replace_emoji(text, replace=_emoji_drop)
    text = text.lower()
    text = _REPEAT_LETTERS.sub(r"\1\1", text)   # "оооочень" -> "оочень"
    text = _REPEAT_PUNCT.sub(r"\1\1", text)     # "!!!!!" -> "!!"
    return _SPACES.sub(" ", text).strip()


def has_emoji(text: str) -> bool:
    return isinstance(text, str) and emoji.emoji_count(text) > 0